"""Deploy BigQuery datasets/tables, or regenerate the reviewable SQL files in bigquery/sql/.

Usage:
  python bigquery/scripts/deploy_bigquery.py --render        # write bigquery/sql/*.sql
  python bigquery/scripts/deploy_bigquery.py --apply         # run DDL on configured backend
  python bigquery/scripts/deploy_bigquery.py --apply --dry-run

Rendering uses the configured project/dataset names (placeholders by default:
``your-gcp-project-id``). CI checks the committed files equal the generator output.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from bigquery import sql_builder as sb  # noqa: E402
from bigquery.loader import deploy_ddl  # noqa: E402
from bigquery.warehouse import warehouse_for  # noqa: E402
from cdc_common.config import PipelineConfig, load_config  # noqa: E402
from cdc_common.logging_utils import get_logger  # noqa: E402

SQL_DIR = ROOT / "bigquery" / "sql"
HEADER = "-- GENERATED by bigquery/scripts/deploy_bigquery.py --render. Do not edit by hand.\n"
log = get_logger("deploy_bigquery")


def render_files(cfg: PipelineConfig) -> dict[str, str]:
    """File name -> SQL text for every committed SQL file."""
    d = sb.BIGQUERY
    files = {
        "create_datasets.sql": ";\n\n".join(sb.build_create_datasets(cfg, d)) + ";\n",
        "create_tables.sql": ";\n\n".join(
            [
                s
                for t in cfg.tables
                for s in (
                    sb.build_create_staging_table(cfg, t, d),
                    sb.build_create_final_table(cfg, t, d),
                )
            ]
            + [sb.build_create_audit_table(cfg, d)]
        )
        + ";\n",
        "apply_soft_deletes.sql": ";\n\n".join(
            f"-- {t.name}\n" + sb.build_apply_deletes(cfg, t, "soft", d) for t in cfg.tables
        )
        + ";\n",
        "apply_hard_deletes.sql": ";\n\n".join(
            f"-- {t.name}\n" + sb.build_apply_deletes(cfg, t, "hard", d) for t in cfg.tables
        )
        + ";\n",
        "audit_insert.sql": sb.build_audit_insert(cfg, d) + ";\n",
    }
    for t in cfg.tables:
        files[f"merge_{t.name}.sql"] = sb.build_merge_upserts(cfg, t, d) + ";\n"
    params = "-- Parameters: @run_id STRING (pipeline run id)\n"
    return {
        name: HEADER + (params if "merge" in name or "deletes" in name else "") + body
        for name, body in files.items()
    }


def main() -> None:
    """CLI entry point."""
    parser = argparse.ArgumentParser()
    parser.add_argument("--render", action="store_true", help="write bigquery/sql/*.sql")
    parser.add_argument("--apply", action="store_true", help="run DDL on the configured backend")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()
    cfg = load_config()

    if args.render:
        SQL_DIR.mkdir(parents=True, exist_ok=True)
        for name, text in render_files(cfg).items():
            (SQL_DIR / name).write_text(text, encoding="utf-8")
            log.info("sql_rendered", extra={"file": f"bigquery/sql/{name}"})
    if args.apply:
        if args.dry_run:
            for stmt in sb.build_all_ddl(cfg, sb.dialect_for(cfg)):
                print(stmt + ";\n")  # noqa: T201 - CLI output
            return
        count = deploy_ddl(cfg, warehouse_for(cfg))
        log.info("ddl_applied", extra={"backend": cfg.bq_backend, "statements": count})
    if not (args.render or args.apply):
        parser.print_help()


if __name__ == "__main__":
    main()
