"""Credential and client setup for the S3 -> GCS transfer.

GCP credentials, in order of preference:
1. Workload Identity Federation (AWS -> GCP): a *credential configuration* JSON
   (``"type": "external_account"``, generated by
   ``gcloud iam workload-identity-pools create-cred-config ... --aws``) stored in AWS Secrets
   Manager. It contains no secret; google-auth exchanges the job's AWS role credentials for a
   short-lived GCP token. No long-lived key exists anywhere.
2. Service-account key JSON in AWS Secrets Manager (fallback; rotate every 90 days).
3. Application Default Credentials (local dev, or an Airflow worker running on GCP).
"""

from __future__ import annotations

import json
import os
from typing import Any

from cdc_common.config import PipelineConfig
from cdc_common.logging_utils import get_logger
from cdc_common.storage import GcsObjectStore, ObjectStore, store_for_uri

log = get_logger("transfer.config")
GCS_SCOPES = ["https://www.googleapis.com/auth/devstorage.read_write"]


def _export_aws_credentials_for_google_auth(region: str) -> None:
    """google-auth's AWS supplier reads AWS_* env vars (or IMDS); populate them from boto3."""
    import boto3

    session = boto3.Session()
    creds = session.get_credentials()
    if creds is None:
        raise RuntimeError("No AWS credentials available for Workload Identity Federation")
    frozen = creds.get_frozen_credentials()
    os.environ["AWS_ACCESS_KEY_ID"] = frozen.access_key or ""
    os.environ["AWS_SECRET_ACCESS_KEY"] = frozen.secret_key or ""
    if frozen.token:
        os.environ["AWS_SESSION_TOKEN"] = frozen.token
    os.environ.setdefault("AWS_REGION", region)


def load_gcp_credentials(secret_id: str, region: str, secrets_client: Any | None = None) -> Any:
    """Return google-auth credentials from Secrets Manager, or None to use ADC."""
    if not secret_id:
        return None
    import google.auth

    if secrets_client is None:
        import boto3

        secrets_client = boto3.client("secretsmanager", region_name=region)
    info = json.loads(secrets_client.get_secret_value(SecretId=secret_id)["SecretString"])
    kind = info.get("type")
    if kind == "external_account":
        _export_aws_credentials_for_google_auth(region)
    elif kind != "service_account":
        raise ValueError(f"Unsupported GCP credential type {kind!r} in secret {secret_id}")
    credentials, _ = google.auth.load_credentials_from_dict(info, scopes=GCS_SCOPES)
    log.info(
        "gcp_credentials_loaded", extra={"event": "gcp_credentials_loaded", "credential_type": kind}
    )
    return credentials


def build_stores(cfg: PipelineConfig) -> tuple[ObjectStore, ObjectStore]:
    """(processed-bucket store, GCS staging store) for the configured environment."""
    source = store_for_uri(cfg.processed_uri)
    if cfg.gcs_staging_uri.startswith("gs://"):
        from google.cloud import storage  # type: ignore[attr-defined]

        credentials = load_gcp_credentials(cfg.gcp_credentials_secret_id, cfg.aws_region)
        client = storage.Client(project=cfg.bq_project, credentials=credentials)
        return source, GcsObjectStore(cfg.gcs_staging_uri.removeprefix("gs://"), client)
    return source, store_for_uri(cfg.gcs_staging_uri)
